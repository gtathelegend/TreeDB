/// Deterministic adaptive plan selector.
///
/// Evaluates validated physical plan alternatives using static costs and runtime feedback,
/// enforcing hysteresis to prevent plan flapping.
#[derive(Debug, Clone)]
pub struct AdaptivePlanSelector {
    config: AdaptiveSelectionConfig,
    metrics: AdaptiveSelectionMetrics,
}

impl Default for AdaptivePlanSelector {
    fn default() -> Self {
        Self::new(AdaptiveSelectionConfig::default())
    }
}

impl AdaptivePlanSelector {
    /// Creates a new `AdaptivePlanSelector` with the provided configuration.
    pub fn new(config: AdaptiveSelectionConfig) -> Self {
        Self {
            config,
            metrics: AdaptiveSelectionMetrics::default(),
        }
    }

    /// Returns the current configuration.
    pub fn config(&self) -> &AdaptiveSelectionConfig {
        &self.config
    }

    /// Sets the configuration.
    pub fn set_config(&mut self, config: AdaptiveSelectionConfig) {
        self.config = config;
    }

    /// Returns recorded telemetry metrics.
    pub fn metrics(&self) -> AdaptiveSelectionMetrics {
        self.metrics
    }

    /// Resets recorded telemetry metrics.
    pub fn reset_metrics(&mut self) {
        self.metrics = AdaptiveSelectionMetrics::default();
    }

    /// Selects the best physical plan from a bounded candidate set.
    ///
    /// # Safety and Invariants
    /// - Only validated candidates (`is_valid() == true`) are eligible.
    /// - Any candidate violating active resource limits is disqualified.
    /// - Ties are broken deterministically by cost, cardinality, access path, and fingerprint hex.
    /// - Switching from `current_plan_fingerprint` requires overcoming the hysteresis threshold.
    #[allow(clippy::too_many_arguments)]
    pub fn select(
        &mut self,
        candidates: &PlanCandidateSet,
        current_plan_fingerprint: Option<&PhysicalPlanFingerprint>,
        feedback: Option<&FeedbackRegistry>,
        param_sig: Option<&ParamPlanningSignature>,
        resource_sig: Option<&ResourcePlanningSignature>,
        stats_gen: u64,
        val_ctx: Option<&PlanValidationContext>,
    ) -> std::result::Result<AdaptiveSelectionResult, PlanValidationError> {
        self.metrics.attempts += 1;
        self.metrics.candidates_evaluated += candidates.len();

        // 1. Collect and ensure validation of candidates
        let mut eligible: Vec<PlanCandidate> = Vec::new();
        for c in candidates.candidates() {
            let mut cand = c.clone();
            if !cand.is_valid() {
                if let Some(ctx) = val_ctx {
                    if cand.validate(ctx).is_err() {
                        continue;
                    }
                } else {
                    continue;
                }
            }

            // 2. Resource compatibility check
            if let Some(active_res) = resource_sig {
                if let Some(cand_res) = &cand.resource_signature {
                    if cand_res.memory_budget_bytes > active_res.memory_budget_bytes
                        || cand_res.max_temp_files > active_res.max_temp_files
                        || cand_res.max_temp_bytes > active_res.max_temp_bytes
                    {
                        // Incompatible resource signature
                        continue;
                    }
                }
            }

            eligible.push(cand);
        }

        if eligible.is_empty() {
            self.metrics.rejections += 1;
            return Err(PlanValidationError::InvalidOperatorContract {
                operator: "AdaptivePlanSelector".to_string(),
                reason: "No validated, resource-compatible physical plan candidates available"
                    .to_string(),
            });
        }

        let validated_count = eligible.len();

        // 3. Compute runtime-feedback adjusted cost and cardinality
        let mut total_obs_used = 0;
        let mut max_confidence = 0.0;

        for cand in &mut eligible {
            let (adj_cost, adj_card, obs_used, conf) = self.calculate_candidate_adjustment(
                cand,
                feedback,
                param_sig,
                resource_sig,
                stats_gen,
            );
            cand.adjusted_cost = adj_cost;
            cand.adjusted_cardinality = adj_card;
            total_obs_used += obs_used;
            if conf > max_confidence {
                max_confidence = conf;
            }
        }
        self.metrics.observations_used += total_obs_used;

        // 4. Deterministic candidate ranking
        eligible.sort_by(|a, b| {
            // Primary: adjusted cost
            let c = a.adjusted_cost.total_cmp(&b.adjusted_cost);
            if c != std::cmp::Ordering::Equal {
                return c;
            }
            // Secondary: adjusted cardinality
            let card = a.adjusted_cardinality.total_cmp(&b.adjusted_cardinality);
            if card != std::cmp::Ordering::Equal {
                return card;
            }
            // Tertiary: ordering guarantee preference
            let ord_a = a.properties.ordering.is_some();
            let ord_b = b.properties.ordering.is_some();
            if ord_a != ord_b {
                return ord_b.cmp(&ord_a);
            }
            // Quaternary: access path preference
            let pref_a = access_path_preference(&a.plan.base_table.access_path);
            let pref_b = access_path_preference(&b.plan.base_table.access_path);
            if pref_a != pref_b {
                return pref_b.cmp(&pref_a);
            }
            // Quinary: canonical fingerprint hex for 100% deterministic tie-breaking
            a.fingerprint.to_hex().cmp(&b.fingerprint.to_hex())
        });

        let candidate_rankings: Vec<(String, f64, f64)> = eligible
            .iter()
            .map(|c| {
                (
                    c.fingerprint.to_hex(),
                    c.adjusted_cost,
                    c.adjusted_cardinality,
                )
            })
            .collect();

        // 5. Evaluate current plan and apply hysteresis
        let best_candidate = eligible[0].clone();

        let (decision, selected_candidate) = if let Some(cur_fp) = current_plan_fingerprint {
            if let Some(cur_cand) = eligible.iter().find(|c| &c.fingerprint == cur_fp) {
                if &best_candidate.fingerprint == cur_fp {
                    // Current plan remains best
                    self.metrics.keeps += 1;
                    (
                        ReplanDecision::KeepCurrentPlan {
                            fingerprint: cur_cand.fingerprint.clone(),
                            reason: "Current plan remains optimal".to_string(),
                        },
                        cur_cand.clone(),
                    )
                } else if best_candidate.adjusted_cost
                    < cur_cand.adjusted_cost * self.config.switch_threshold
                {
                    // Meaningful improvement exceeding hysteresis threshold
                    let improvement = (cur_cand.adjusted_cost - best_candidate.adjusted_cost)
                        / cur_cand.adjusted_cost.max(0.001);
                    self.metrics.switches += 1;
                    (
                        ReplanDecision::SwitchToAlternative {
                            from: cur_cand.fingerprint.clone(),
                            to: best_candidate.fingerprint.clone(),
                            improvement_ratio: improvement,
                            reason: format!(
                                "Alternative has lower adjusted cost ({:.2} vs {:.2})",
                                best_candidate.adjusted_cost, cur_cand.adjusted_cost
                            ),
                        },
                        best_candidate,
                    )
                } else {
                    // Improvement did not overcome hysteresis threshold
                    self.metrics.keeps += 1;
                    (
                        ReplanDecision::KeepCurrentPlan {
                            fingerprint: cur_cand.fingerprint.clone(),
                            reason: format!(
                                "Improvement ({:.2} vs {:.2}) below hysteresis threshold ({:.2})",
                                best_candidate.adjusted_cost,
                                cur_cand.adjusted_cost,
                                self.config.switch_threshold
                            ),
                        },
                        cur_cand.clone(),
                    )
                }
            } else {
                // Current plan not among validated candidates
                self.metrics.switches += 1;
                (
                    ReplanDecision::SwitchToAlternative {
                        from: cur_fp.clone(),
                        to: best_candidate.fingerprint.clone(),
                        improvement_ratio: 1.0,
                        reason: "Current plan not in candidate set or invalid".to_string(),
                    },
                    best_candidate,
                )
            }
        } else {
            // First execution; pick best candidate directly
            self.metrics.switches += 1;
            (
                ReplanDecision::SwitchToAlternative {
                    from: best_candidate.fingerprint.clone(),
                    to: best_candidate.fingerprint.clone(),
                    improvement_ratio: 0.0,
                    reason: "Initial candidate selection".to_string(),
                },
                best_candidate,
            )
        };

        let selected_fingerprint = selected_candidate.fingerprint.clone();
        let selected_plan = selected_candidate.validated.clone().unwrap();

        let diagnostics = AdaptiveSelectionDiagnostics {
            candidates_considered: candidates.len(),
            validated_candidates: validated_count,
            current_fingerprint: current_plan_fingerprint.map(|fp| fp.to_hex()),
            selected_fingerprint: Some(selected_fingerprint.to_hex()),
            decision: format!("{decision}"),
            reason: match &decision {
                ReplanDecision::KeepCurrentPlan { reason, .. }
                | ReplanDecision::SwitchToAlternative { reason, .. }
                | ReplanDecision::Reoptimize { reason }
                | ReplanDecision::Reject { reason } => reason.clone(),
            },
            adjusted_cost: selected_candidate.adjusted_cost,
            observations_used: total_obs_used,
            confidence: max_confidence,
            candidate_rankings,
        };

        Ok(AdaptiveSelectionResult {
            decision,
            selected_plan,
            selected_fingerprint,
            diagnostics,
        })
    }

    /// Computes runtime-feedback adjusted cost and cardinality for a candidate.
    fn calculate_candidate_adjustment(
        &self,
        candidate: &PlanCandidate,
        feedback_reg: Option<&FeedbackRegistry>,
        param_sig: Option<&ParamPlanningSignature>,
        resource_sig: Option<&ResourcePlanningSignature>,
        stats_gen: u64,
    ) -> (f64, f64, usize, f64) {
        if !self.config.enabled {
            return (
                candidate.estimated_cost,
                candidate.estimated_cardinality,
                0,
                0.0,
            );
        }

        let reg = match feedback_reg {
            Some(r) => r,
            None => {
                return (
                    candidate.estimated_cost,
                    candidate.estimated_cardinality,
                    0,
                    0.0,
                )
            }
        };

        // 1. Try candidate fingerprint key lookup
        let mut matching_entry = None;

        // Try candidate specific key
        let fp_key = FeedbackKey::new(
            FeedbackContext::Scan {
                table_name: candidate.plan.base_table.table_name.clone(),
                predicate_repr: candidate
                    .plan
                    .base_table
                    .residual_filter
                    .as_ref()
                    .map(|f| f.to_string())
                    .unwrap_or_default(),
                access_path_repr: candidate.plan.base_table.access_path.to_string(),
            },
            param_sig.cloned(),
            stats_gen,
        )
        .with_resource_signature(resource_sig.cloned())
        .with_physical_fingerprint(Some(candidate.fingerprint.clone()));

        if let Some(entry) = reg.get(&fp_key) {
            matching_entry = Some(entry);
        } else {
            // 2. Fall back to structural operator keys
            let structural_key = FeedbackKey::scan(
                &candidate.plan.base_table.table_name,
                candidate.plan.base_table.access_path.to_string(),
                candidate
                    .plan
                    .base_table
                    .residual_filter
                    .as_ref()
                    .map(|f| f.to_string())
                    .unwrap_or_default(),
                param_sig.cloned(),
                stats_gen,
            )
            .with_resource_signature(resource_sig.cloned());

            if let Some(entry) = reg.get(&structural_key) {
                matching_entry = Some(entry);
            }
        }

        let entry = match matching_entry {
            Some(e) => e,
            None => {
                return (
                    candidate.estimated_cost,
                    candidate.estimated_cardinality,
                    0,
                    0.0,
                )
            }
        };

        if entry.observation_count < self.config.min_observations {
            return (
                candidate.estimated_cost,
                candidate.estimated_cardinality,
                entry.observation_count,
                0.0,
            );
        }

        // Validate entry numbers: discard malformed, NaN, negative
        if !entry.effective_cardinality.is_finite() || entry.effective_cardinality < 0.0 {
            return (
                candidate.estimated_cost,
                candidate.estimated_cardinality,
                entry.observation_count,
                0.0,
            );
        }

        let base_card = candidate.estimated_cardinality.max(1.0);
        let error_ratio = (entry.effective_cardinality / base_card).clamp(
            self.config.max_cost_adjustment_ratio.recip(),
            self.config.max_cost_adjustment_ratio,
        );

        let confidence = FeedbackConfidence::compute(entry.observation_count, error_ratio);
        if confidence.score < self.config.min_confidence {
            return (
                candidate.estimated_cost,
                candidate.estimated_cardinality,
                entry.observation_count,
                confidence.score,
            );
        }

        // Apply EWMA adjustment scaled by confidence
        let adjusted_cardinality = (candidate.estimated_cardinality
            * (1.0 + (error_ratio - 1.0) * confidence.score))
            .max(0.0);

        let mut adjusted_cost =
            (candidate.estimated_cost * (1.0 + (error_ratio - 1.0) * confidence.score)).max(0.01);

        // Spill penalty if resource feedback indicates disk spill
        if let Some(res) = &entry.resource_feedback {
            if res.spill_status == SpillStatus::Spilled {
                let spill_penalty = 50.0 + (res.effective_spill_bytes * 0.001);
                adjusted_cost += spill_penalty * confidence.score;
            }
        }

        (
            adjusted_cost,
            adjusted_cardinality,
            entry.observation_count,
            confidence.score,
        )
    }
}

/// Helper returning relative desirability of an access path for deterministic tie-breaking.
fn access_path_preference(ap: &AccessPath) -> u8 {
    match ap {
        AccessPath::IndexOnlyScan { .. } => 4,
        AccessPath::SecondaryIndexScan { .. } => 3,
        AccessPath::PrimaryRangeScan { .. } => 2,
        AccessPath::FullTableScan => 1,
        _ => 0,
    }
}
