/// Default maximum number of physical plan alternatives tracked in a candidate set.
pub const DEFAULT_MAX_CANDIDATES: usize = 16;

/// Default minimum number of observations required before adaptive selection considers feedback.
pub const DEFAULT_MIN_OBSERVATIONS: usize = 2;

/// Default cost improvement factor required to overcome hysteresis (e.g. 0.85 = 15% cheaper).
pub const DEFAULT_SWITCH_THRESHOLD: f64 = 0.85;

/// Default minimum confidence score required to adjust planning estimates.
pub const DEFAULT_MIN_CONFIDENCE: f64 = 0.5;

/// Upper multiplier clamp for cost adjustment via feedback error.
pub const DEFAULT_MAX_COST_ADJUSTMENT_RATIO: f64 = 20.0;

/// Explicit states representing a query plan's progression through TreeDB's lifecycle.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum PlanLifecycleState {
    /// Initial physical plan generated by optimizer or memo exploration. Unvalidated.
    Candidate,
    /// Physical plan that has passed full contract and safety validation.
    Validated,
    /// Validated plan stored in the statement/plan cache.
    Cached,
    /// Validated plan chosen by the adaptive selector for the current execution.
    Selected,
    /// Plan currently active in executor pipeline.
    Executing,
    /// Execution completed; runtime metrics recorded and available for feedback.
    Completed,
    /// Plan invalidated by schema/index/stats change or replan trigger.
    Invalidated,
}

impl fmt::Display for PlanLifecycleState {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Candidate => write!(f, "Candidate"),
            Self::Validated => write!(f, "Validated"),
            Self::Cached => write!(f, "Cached"),
            Self::Selected => write!(f, "Selected"),
            Self::Executing => write!(f, "Executing"),
            Self::Completed => write!(f, "Completed"),
            Self::Invalidated => write!(f, "Invalidated"),
        }
    }
}

/// A physical execution plan alternative participating in adaptive selection.
#[derive(Debug, Clone, PartialEq)]
pub struct PlanCandidate {
    /// The physical execution plan.
    pub plan: PhysicalPlan,
    /// Deterministic canonical physical plan fingerprint for identity and feedback mapping.
    pub fingerprint: PhysicalPlanFingerprint,
    /// Physical properties guaranteed by this plan.
    pub properties: PhysicalProperties,
    /// Base cost estimate computed by static cost model.
    pub estimated_cost: f64,
    /// Base cardinality estimate computed by static optimizer.
    pub estimated_cardinality: f64,
    /// Cost estimate adjusted by runtime feedback.
    pub adjusted_cost: f64,
    /// Cardinality estimate adjusted by runtime feedback.
    pub adjusted_cardinality: f64,
    /// Resource planning signature required by this plan (if resource-sensitive).
    pub resource_signature: Option<ResourcePlanningSignature>,
    /// Type-level proof of physical plan validation if validated.
    pub validated: Option<ValidatedPhysicalPlan>,
    /// Current lifecycle state.
    pub state: PlanLifecycleState,
    /// Human-readable explanation of this physical choice.
    pub description: String,
}

impl PlanCandidate {
    /// Constructs a new candidate from a physical plan and base estimates.
    pub fn new(
        plan: PhysicalPlan,
        cost: f64,
        cardinality: f64,
        properties: PhysicalProperties,
        description: impl Into<String>,
    ) -> Self {
        let fingerprint = plan.fingerprint();
        Self {
            plan,
            fingerprint,
            properties,
            estimated_cost: cost.max(0.0),
            estimated_cardinality: cardinality.max(0.0),
            adjusted_cost: cost.max(0.0),
            adjusted_cardinality: cardinality.max(0.0),
            resource_signature: None,
            validated: None,
            state: PlanLifecycleState::Candidate,
            description: description.into(),
        }
    }

    /// Constructs a candidate with a specific resource planning signature.
    pub fn with_resource_signature(mut self, res_sig: Option<ResourcePlanningSignature>) -> Self {
        self.fingerprint =
            PhysicalPlanFingerprint::from_plan_with_resources(&self.plan, res_sig.as_ref());
        self.resource_signature = res_sig;
        self
    }

    /// Constructs a candidate from a memo physical alternative.
    pub fn from_alternative(alt: &PhysicalAlternative) -> Self {
        Self {
            plan: alt.plan.clone(),
            fingerprint: alt.plan_fingerprint.clone(),
            properties: alt.properties.clone(),
            estimated_cost: alt.cost.max(0.0),
            estimated_cardinality: alt.cardinality.max(0.0),
            adjusted_cost: alt.cost.max(0.0),
            adjusted_cardinality: alt.cardinality.max(0.0),
            resource_signature: None,
            validated: None,
            state: PlanLifecycleState::Candidate,
            description: alt.description.clone(),
        }
    }

    /// Validates this candidate against the specified validation context.
    pub fn validate(
        &mut self,
        ctx: &PlanValidationContext,
    ) -> std::result::Result<&ValidatedPhysicalPlan, PlanValidationError> {
        match PhysicalPlanValidator::validate(&self.plan, ctx) {
            Ok(v) => {
                self.validated = Some(v);
                self.state = PlanLifecycleState::Validated;
                Ok(self.validated.as_ref().unwrap())
            }
            Err(e) => {
                self.validated = None;
                self.state = PlanLifecycleState::Invalidated;
                Err(e)
            }
        }
    }

    /// Returns `true` if this candidate has passed validation and is eligible for selection.
    pub fn is_valid(&self) -> bool {
        self.validated.is_some() && self.state != PlanLifecycleState::Invalidated
    }

    /// Marks the candidate as selected for execution.
    pub fn mark_selected(&mut self) {
        if self.is_valid() {
            self.state = PlanLifecycleState::Selected;
        }
    }

    /// Marks the candidate as currently executing.
    pub fn mark_executing(&mut self) {
        self.state = PlanLifecycleState::Executing;
    }

    /// Marks the candidate as completed execution.
    pub fn mark_completed(&mut self) {
        self.state = PlanLifecycleState::Completed;
    }

    /// Marks the candidate as cached.
    pub fn mark_cached(&mut self) {
        if self.is_valid() {
            self.state = PlanLifecycleState::Cached;
        }
    }

    /// Marks the candidate as invalidated.
    pub fn mark_invalidated(&mut self) {
        self.validated = None;
        self.state = PlanLifecycleState::Invalidated;
    }

    /// Returns a reference to the underlying physical plan.
    pub fn plan(&self) -> &PhysicalPlan {
        &self.plan
    }

    /// Returns a reference to the physical plan fingerprint.
    pub fn fingerprint(&self) -> &PhysicalPlanFingerprint {
        &self.fingerprint
    }
}

/// A bounded collection of physical plan alternatives for adaptive selection.
#[derive(Debug, Clone, PartialEq)]
pub struct PlanCandidateSet {
    candidates: Vec<PlanCandidate>,
    max_candidates: usize,
}

impl Default for PlanCandidateSet {
    fn default() -> Self {
        Self::new(DEFAULT_MAX_CANDIDATES)
    }
}

impl PlanCandidateSet {
    /// Creates a new candidate set with a maximum candidate limit.
    pub fn new(max_candidates: usize) -> Self {
        Self {
            candidates: Vec::new(),
            max_candidates: max_candidates.max(1),
        }
    }

    /// Adds a candidate to the set, enforcing deduplication and bounded capacity.
    ///
    /// If a candidate with the same fingerprint already exists, retains the one with lower cost.
    /// If capacity is exceeded, prunes the candidate with the highest estimated cost.
    pub fn add_candidate(&mut self, candidate: PlanCandidate) -> bool {
        // Check if candidate with same fingerprint exists
        if let Some(pos) = self
            .candidates
            .iter()
            .position(|c| c.fingerprint == candidate.fingerprint)
        {
            if candidate.estimated_cost < self.candidates[pos].estimated_cost {
                self.candidates[pos] = candidate;
                return true;
            }
            return false;
        }

        if self.candidates.len() < self.max_candidates {
            self.candidates.push(candidate);
            return true;
        }

        // Bounded pruning: find worst candidate by estimated_cost
        let mut worst_idx = 0;
        let mut worst_cost = self.candidates[0].estimated_cost;
        for (i, c) in self.candidates.iter().enumerate().skip(1) {
            if c.estimated_cost > worst_cost {
                worst_cost = c.estimated_cost;
                worst_idx = i;
            }
        }

        if candidate.estimated_cost < worst_cost {
            self.candidates[worst_idx] = candidate;
            true
        } else {
            false
        }
    }

    /// Constructs a candidate set from a slice of memo alternatives.
    pub fn from_alternatives(alts: &[PhysicalAlternative], max_candidates: usize) -> Self {
        let mut set = Self::new(max_candidates);
        for alt in alts {
            set.add_candidate(PlanCandidate::from_alternative(alt));
        }
        set
    }

    /// Constructs a candidate set from a memo equivalence group.
    pub fn from_memo_group(group: &MemoGroup, max_candidates: usize) -> Self {
        Self::from_alternatives(&group.alternatives, max_candidates)
    }

    /// Validates all candidates against the given validation context.
    ///
    /// Candidates failing validation are marked `Invalidated`.
    pub fn validate_all(&mut self, ctx: &PlanValidationContext) {
        for candidate in &mut self.candidates {
            let _ = candidate.validate(ctx);
        }
    }

    /// Returns all candidates that have successfully passed validation.
    pub fn validated_candidates(&self) -> Vec<&PlanCandidate> {
        self.candidates.iter().filter(|c| c.is_valid()).collect()
    }

    /// Returns a slice of all candidates.
    pub fn candidates(&self) -> &[PlanCandidate] {
        &self.candidates
    }

    /// Returns a mutable slice of all candidates.
    pub fn candidates_mut(&mut self) -> &mut [PlanCandidate] {
        &mut self.candidates
    }

    /// Finds a candidate by its physical plan fingerprint.
    pub fn find_by_fingerprint(&self, fp: &PhysicalPlanFingerprint) -> Option<&PlanCandidate> {
        self.candidates.iter().find(|c| &c.fingerprint == fp)
    }

    /// Finds a mutable candidate by its physical plan fingerprint.
    pub fn find_by_fingerprint_mut(
        &mut self,
        fp: &PhysicalPlanFingerprint,
    ) -> Option<&mut PlanCandidate> {
        self.candidates.iter_mut().find(|c| &c.fingerprint == fp)
    }

    /// Returns the number of candidates in the set.
    pub fn len(&self) -> usize {
        self.candidates.len()
    }

    /// Returns `true` if the candidate set is empty.
    pub fn is_empty(&self) -> bool {
        self.candidates.is_empty()
    }
}

/// Normalized runtime observation interface for feeding back execution metrics.
#[derive(Debug, Clone, PartialEq)]
pub struct PlanObservation {
    /// Physical plan fingerprint identifying the executed plan strategy.
    pub physical_fingerprint: PhysicalPlanFingerprint,
    /// Logical relational operator or table context.
    pub logical_context: Option<String>,
    /// Parameter planning signature isolating parameterized shapes.
    pub param_signature: Option<ParamPlanningSignature>,
    /// Resource planning signature at execution time.
    pub resource_signature: Option<ResourcePlanningSignature>,
    /// Optimizer-estimated output rows.
    pub estimated_rows: f64,
    /// Runtime actual output rows observed.
    pub actual_rows: f64,
    /// Estimated plan cost.
    pub estimated_cost: Option<f64>,
    /// Observed execution time in microseconds.
    pub actual_time_us: Option<u64>,
    /// Peak memory consumed in bytes.
    pub peak_memory_bytes: Option<usize>,
    /// Disk spill bytes if external spill occurred.
    pub spill_bytes: Option<usize>,
    /// Temporary files opened for spill runs.
    pub temporary_files: Option<usize>,
    /// Observation timestamp or sequence number.
    pub observation_time: u64,
}

impl PlanObservation {
    /// Creates a basic valid plan observation.
    pub fn new(
        physical_fingerprint: PhysicalPlanFingerprint,
        estimated_rows: f64,
        actual_rows: f64,
    ) -> Self {
        Self {
            physical_fingerprint,
            logical_context: None,
            param_signature: None,
            resource_signature: None,
            estimated_rows: estimated_rows.max(0.0),
            actual_rows: actual_rows.max(0.0),
            estimated_cost: None,
            actual_time_us: None,
            peak_memory_bytes: None,
            spill_bytes: None,
            temporary_files: None,
            observation_time: 0,
        }
    }

    /// Returns `true` if this observation contains valid, finite, non-corrupted metrics.
    pub fn is_valid(&self) -> bool {
        self.estimated_rows.is_finite()
            && self.estimated_rows >= 0.0
            && self.actual_rows.is_finite()
            && self.actual_rows >= 0.0
            && self
                .estimated_cost
                .map(|c| c.is_finite() && c >= 0.0)
                .unwrap_or(true)
    }

    /// Computes the estimation error ratio (`actual / estimated` or `estimated / actual`).
    pub fn error_ratio(&self) -> f64 {
        compute_estimation_error(self.estimated_rows, self.actual_rows)
    }
}

/// Bounded confidence score derived from observation count and error stability.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct FeedbackConfidence {
    /// Bounded confidence metric between 0.0 and 1.0.
    pub score: f64,
    /// Number of observations recorded.
    pub observation_count: usize,
    /// Error stability score between 0.0 and 1.0.
    pub stability: f64,
}

impl FeedbackConfidence {
    /// Computes a bounded confidence score based on observation count.
    pub fn compute(observation_count: usize, _error_ratio: f64) -> Self {
        let count_weight =
            (observation_count as f64 / (observation_count as f64 + 1.0)).clamp(0.0, 1.0);
        Self {
            score: count_weight,
            observation_count,
            stability: 1.0,
        }
    }
}

/// Configuration settings governing adaptive candidate selection and hysteresis.
#[derive(Debug, Clone, PartialEq)]
pub struct AdaptiveSelectionConfig {
    /// Minimum observation count required before considering feedback.
    pub min_observations: usize,
    /// Threshold multiplier for switching plans (e.g. 0.85 = candidate must be >=15% cheaper).
    pub switch_threshold: f64,
    /// Minimum confidence required to adjust planning estimates.
    pub min_confidence: f64,
    /// Maximum candidates retained in candidate sets.
    pub max_candidates: usize,
    /// Whether adaptive plan selection is enabled.
    pub enabled: bool,
    /// Maximum cost adjustment ratio clamp (prevents single-outlier distortion).
    pub max_cost_adjustment_ratio: f64,
}

impl Default for AdaptiveSelectionConfig {
    fn default() -> Self {
        Self {
            min_observations: DEFAULT_MIN_OBSERVATIONS,
            switch_threshold: DEFAULT_SWITCH_THRESHOLD,
            min_confidence: DEFAULT_MIN_CONFIDENCE,
            max_candidates: DEFAULT_MAX_CANDIDATES,
            enabled: true,
            max_cost_adjustment_ratio: DEFAULT_MAX_COST_ADJUSTMENT_RATIO,
        }
    }
}

/// Decision reached during adaptive candidate selection.
#[derive(Debug, Clone, PartialEq)]
pub enum ReplanDecision {
    /// Retain the current physical plan.
    KeepCurrentPlan {
        /// Fingerprint of the retained plan.
        fingerprint: PhysicalPlanFingerprint,
        /// Explanation for keeping current plan.
        reason: String,
    },
    /// Switch to a superior valid alternative.
    SwitchToAlternative {
        /// Fingerprint of previously active plan.
        from: PhysicalPlanFingerprint,
        /// Fingerprint of newly selected plan.
        to: PhysicalPlanFingerprint,
        /// Relative improvement factor (`(cost_old - cost_new) / cost_old`).
        improvement_ratio: f64,
        /// Explanation for the switch.
        reason: String,
    },
    /// Trigger next-execution reoptimization.
    Reoptimize {
        /// Explanation why reoptimization is requested.
        reason: String,
    },
    /// Reject selection because no valid candidate satisfies constraints.
    Reject {
        /// Reason for rejection.
        reason: String,
    },
}

impl fmt::Display for ReplanDecision {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::KeepCurrentPlan {
                fingerprint,
                reason,
            } => {
                write!(
                    f,
                    "KeepCurrentPlan(fingerprint={}, reason={})",
                    fingerprint.to_hex(),
                    reason
                )
            }
            Self::SwitchToAlternative {
                from,
                to,
                improvement_ratio,
                reason,
            } => write!(
                f,
                "SwitchToAlternative(from={}, to={}, improvement={:.2}%, reason={})",
                from.to_hex(),
                to.to_hex(),
                improvement_ratio * 100.0,
                reason
            ),
            Self::Reoptimize { reason } => write!(f, "Reoptimize(reason={})", reason),
            Self::Reject { reason } => write!(f, "Reject(reason={})", reason),
        }
    }
}

/// Deterministic diagnostics generated during adaptive candidate selection.
#[derive(Debug, Clone, PartialEq)]
pub struct AdaptiveSelectionDiagnostics {
    /// Total candidates evaluated.
    pub candidates_considered: usize,
    /// Total candidates passing safety validation.
    pub validated_candidates: usize,
    /// Fingerprint of the current plan before selection (if any).
    pub current_fingerprint: Option<String>,
    /// Fingerprint of the selected winning plan.
    pub selected_fingerprint: Option<String>,
    /// Decision category.
    pub decision: String,
    /// Human-readable explanation.
    pub reason: String,
    /// Final adjusted cost of the selected plan.
    pub adjusted_cost: f64,
    /// Feedback observations utilized.
    pub observations_used: usize,
    /// Confidence score applied.
    pub confidence: f64,
    /// Deterministic candidate rankings: `(fingerprint_hex, adjusted_cost, adjusted_cardinality)`.
    pub candidate_rankings: Vec<(String, f64, f64)>,
}

impl fmt::Display for AdaptiveSelectionDiagnostics {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(f, "Adaptive Selection:")?;
        writeln!(
            f,
            "  candidates: {} (validated: {})",
            self.candidates_considered, self.validated_candidates
        )?;
        if let Some(cur) = &self.current_fingerprint {
            writeln!(f, "  current: {cur}")?;
        }
        if let Some(sel) = &self.selected_fingerprint {
            writeln!(f, "  selected: {sel}")?;
        }
        writeln!(f, "  decision: {}", self.decision)?;
        writeln!(f, "  reason: {}", self.reason)?;
        writeln!(f, "  adjusted_cost: {:.2}", self.adjusted_cost)?;
        write!(
            f,
            "  observations: {} (confidence: {:.2})",
            self.observations_used, self.confidence
        )
    }
}

