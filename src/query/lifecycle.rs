//! Unified Plan Lifecycle, Bounded Candidate Sets, and Safe Adaptive Selection.
//!
//! Consolidates the query optimizer memo, physical-plan fingerprints, safety validator,
//! plan cache, resource signatures, and runtime cardinality/resource feedback into a
//! deterministic execution lifecycle:
//!
//! ```text
//! Candidate Plans
//!       ↓
//! Canonical Physical Identity
//!       ↓
//! Validation
//!       ↓
//! Cost / Cardinality
//!       ↓
//! Plan Cache
//!       ↓
//! Runtime Feedback
//!       ↓
//! Adaptive Selection
//!       ↓
//! Validation Again
//!       ↓
//! Execution
//! ```
//!
//! # Core Invariants
//! 1. **No Unvalidated Execution**: Every plan selected or retrieved from cache must pass
//!    physical-plan validation before execution.
//! 2. **No Mid-Query Mutation**: Runtime feedback informs choice between executions
//!    (Execution N → Feedback → Adaptive Selection → Execution N+1). A running pipeline is never mutated.
//! 3. **Feedback Is Advisory**: Corrupted, missing, or extreme feedback is discarded or clamped.
//!    Query semantics never depend on feedback presence or accuracy.
//! 4. **Hysteresis & Anti-Flapping**: Switching away from a current plan requires a deterministic,
//!    meaningful improvement ratio to prevent plan flapping.

